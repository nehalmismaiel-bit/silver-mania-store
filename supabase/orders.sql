-- SILVER MANIA: customer orders
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  phone text not null,
  address text not null,
  notes text,
  items jsonb not null,
  total numeric(12,2) not null check (total >= 0),
  payment_method text not null default 'cash_on_delivery',
  status text not null default 'new'
    check (status in ('new','confirmed','processing','shipped','completed','cancelled')),
  created_at timestamptz not null default now()
);

alter table public.orders enable row level security;

grant insert on public.orders to anon, authenticated;
grant select, update on public.orders to authenticated;
grant usage, select on sequence public.orders_order_number_seq to anon, authenticated;

drop policy if exists "Anyone can place an order" on public.orders;
create policy "Anyone can place an order"
  on public.orders for insert
  to anon, authenticated
  with check (
    length(trim(customer_name)) between 2 and 120
    and length(regexp_replace(phone, '\\D', '', 'g')) between 8 and 15
    and length(trim(address)) between 5 and 500
    and jsonb_typeof(items) = 'array'
    and jsonb_array_length(items) > 0
  );

drop policy if exists "Store admins can view orders" on public.orders;
create policy "Store admins can view orders"
  on public.orders for select
  to authenticated
  using (auth.uid() is not null);

drop policy if exists "Store admins can update orders" on public.orders;
create policy "Store admins can update orders"
  on public.orders for update
  to authenticated
  using (auth.uid() is not null)
  with check (auth.uid() is not null);
